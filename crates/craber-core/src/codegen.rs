//! The frontend sources generated from the Rust definitions.
//!
//! Colours, node sizes and the wire version are defined once, in Rust, because
//! the binary has to render with no web assets in reach. The browser needs the
//! same numbers, so they are written out rather than restated, and CI fails if
//! what is checked in has gone stale.
//!
//! # Why generating is a test
//!
//! `just bindings` is `cargo test -p craber-core`, and the writing happens in
//! this module's `tests`. That is not a choice: `web/src/types` is written by
//! ts-rs, whose `#[ts(export)]` emits a test per type, so `cargo test` is
//! already the step that regenerates the frontend's Rust-derived sources.
//! Writing the tokens from a separate `cargo run` would mean two commands and
//! two ways to be stale, for the same effect.
//!
//! It being a *unit* test is the part that is a choice. As an integration test
//! it had to reach these functions from outside the crate, which made a
//! generator part of a published crate's public API.
//!
//! This is separate from [`theme`](crate::theme) and
//! [`geometry`](crate::geometry) because emitting CSS and TypeScript is a
//! different job from being a palette: the values are what CrabER draws with,
//! and this is a translation of them into two other languages.

use std::fmt::Write as _;

use crate::geometry::metrics;
use crate::theme::{Chrome, Theme};

/// `web/src/generated/tokens.css` — the `:root` block the web app imports.
///
/// Only the dark theme is emitted: the stylesheet has no light mode yet, and
/// adding one should be a second `:root` block written from [`Theme::light`]
/// rather than a rewrite (see the note at the top of `web/src/theme.css`).
pub(crate) fn tokens_css() -> String {
    let theme = Theme::dark();
    let chrome = Chrome::dark();

    let mut out = String::new();
    out.push_str(
        "/*\n * Generated by `just bindings` from crates/craber-core/src/codegen.rs.\n\
         \x20* Do not edit: change the Rust definition and regenerate.\n */\n\n:root {\n  \
         color-scheme: dark;\n\n",
    );
    for (name, value) in theme.tokens().into_iter().chain(chrome.tokens()) {
        let _ = writeln!(out, "  {name}: {value};");
    }
    out.push('\n');
    for (name, value) in [
        ("--craber-node-width", metrics::NODE_WIDTH),
        ("--craber-node-header", metrics::HEADER_CONTENT),
        ("--craber-node-row", metrics::ROW_CONTENT),
        ("--craber-sidebar-width", metrics::SIDEBAR_WIDTH),
        ("--craber-radius", metrics::RADIUS),
    ] {
        let _ = writeln!(out, "  {name}: {value}px;");
    }
    out.push_str("}\n");
    out
}

/// `web/src/generated/metrics.ts` — what the frontend needs from Rust that is
/// not a type and not a CSS custom property.
///
/// Only the wire version. The node metrics used to be emitted here too and
/// nothing imported them: the browser sizes a node from `--craber-node-*` in
/// [`tokens_css`], which is the copy that is actually load-bearing. TypeScript
/// cannot see an unused *export*, so they would have gone on being generated
/// and read by nobody. Anything that needs a number rather than a custom
/// property belongs here, and should be added back when something does.
pub(crate) fn metrics_ts() -> String {
    format!(
        "// Generated by `just bindings` from crates/craber-core/src/codegen.rs.\n\
         // Do not edit: change the Rust definition and regenerate.\n\
         \n\
         /** The `schema.json` shape this build reads. See `SCHEMA_VERSION` in ir/schema.rs. */\n\
         export const SCHEMA_VERSION = {version};\n",
        version = crate::ir::SCHEMA_VERSION,
    )
}

#[cfg(test)]
mod tests {
    use std::path::{Path, PathBuf};

    use super::{metrics_ts, tokens_css};

    /// `web/src/generated/`, relative to this crate.
    fn generated_dir() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/src/generated")
    }

    /// Write `contents` to `path` only when it differs, so a no-op run does not
    /// touch mtimes and set Vite rebuilding.
    fn write_if_changed(path: &Path, contents: &str) {
        if std::fs::read_to_string(path).is_ok_and(|existing| existing == contents) {
            return;
        }
        std::fs::create_dir_all(path.parent().expect("a parent directory"))
            .expect("creating web/src/generated");
        std::fs::write(path, contents)
            .unwrap_or_else(|e| panic!("writing {}: {e}", path.display()));
    }

    /// The generator. See the module docs for why it is a test.
    ///
    /// The colours and node metrics have to be identical on both sides of
    /// `schema.json`: the layout positions a node from these numbers and the
    /// browser sizes it from them, so a disagreement is a diagram with
    /// overlapping tables or — as actually happened with the foreign-key glyph
    /// — one schema drawn in two different colours.
    #[test]
    fn export_tokens() {
        let dir = generated_dir();
        write_if_changed(&dir.join("tokens.css"), &tokens_css());
        write_if_changed(&dir.join("metrics.ts"), &metrics_ts());
    }

    /// The generated stylesheet is only useful if it actually carries every
    /// token the app reads, so spot-check the ones a drift would be silent
    /// about.
    #[test]
    fn the_generated_stylesheet_carries_the_tokens_the_app_reads() {
        let css = tokens_css();
        for token in [
            "--craber-accent",
            "--craber-glyph-fk",
            "--craber-node-width",
            "--craber-node-header",
            "--craber-node-row",
            "--craber-sidebar-width",
            "--craber-radius",
            "--craber-font-mono",
        ] {
            assert!(css.contains(token), "{token} is missing from tokens.css");
        }
    }

    /// `metrics.ts` is where the frontend learns which `schema.json` it can
    /// read, so the number in it has to be the one the IR is serialising.
    #[test]
    fn the_generated_metrics_carry_the_schema_version() {
        let ts = metrics_ts();
        assert!(
            ts.contains(&format!(
                "export const SCHEMA_VERSION = {};",
                crate::SCHEMA_VERSION
            )),
            "metrics.ts does not state SCHEMA_VERSION {}:\n{ts}",
            crate::SCHEMA_VERSION
        );
    }
}
