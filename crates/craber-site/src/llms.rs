//! `llms.txt`: the index an AI agent reads before anything else on a site.
//!
//! The convention (<https://llmstxt.org>) is a Markdown file at the site root
//! that says what the site is and links to text versions of it. For a diagram
//! the text version is `schema.md`; the page itself is a canvas an agent cannot
//! read.

use craber_core::{SCHEMA_FILE, SCHEMA_VERSION, Schema};

/// The schema as Markdown, which `llms.txt` points at.
pub(crate) const MARKDOWN_FILE: &str = "schema.md";

pub(crate) const LLMS_FILE: &str = "llms.txt";

/// Links are relative, like the bundle's `./assets/`, so the file is right
/// under any base path without knowing it.
pub(crate) fn llms_txt(schema: &Schema) -> String {
    let name = &schema.name;
    let tables = schema.tables.len();
    let plural = if tables == 1 { "" } else { "s" };
    format!(
        "# {name}\n\
         \n\
         > ER diagram of the `{name}` database schema ({tables} table{plural}), generated by CrabER.\n\
         \n\
         ## Schema\n\
         \n\
         - [{MARKDOWN_FILE}]({MARKDOWN_FILE}): every table, column, key, index and enum as Markdown\n\
         - [{SCHEMA_FILE}]({SCHEMA_FILE}): the same as JSON, with diagram coordinates \
         (CrabER schema.json version {SCHEMA_VERSION})\n"
    )
}

#[cfg(test)]
mod tests {
    use super::llms_txt;
    use craber_core::{Schema, Table};

    #[test]
    fn links_relatively_to_the_text_versions() {
        let mut schema = Schema::new("shop");
        schema.tables = vec![Table::new("users")];
        let text = llms_txt(&schema);
        assert!(text.starts_with("# shop\n"), "{text}");
        assert!(text.contains("(1 table)"), "{text}");
        assert!(text.contains("](schema.md)"), "{text}");
        assert!(text.contains("](schema.json)"), "{text}");
    }
}
