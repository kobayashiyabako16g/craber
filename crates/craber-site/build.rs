//! Embeds the built web bundle into the binary.
//!
//! `craber build` and `craber serve` have to hand out a finished site from a
//! single binary, so the bundle is compiled in rather than looked up on disk at
//! run time. But the Rust build must not require Node — CI builds and tests the
//! workspace with no pnpm anywhere — so a missing bundle is not an error here:
//! it produces an empty bundle, and `craber_site` then refuses at run time with
//! a message telling the user to build it. A binary that cannot publish a site
//! is better than a CI job that cannot compile one.
//!
//! It does emit a `cargo:warning` in that case. The failure is otherwise
//! completely silent until someone runs the binary, which is a poor way to
//! learn that the release you just cut cannot do half its job.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-env-changed=CRABER_WEB_DIST");

    // Watch every candidate, not just the one that won: creating `web/dist` for
    // the first time has to trigger a rebuild, and it does not exist yet to be
    // watched by the winner.
    let manifest =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    for dir in [manifest.join("bundle"), manifest.join("../../web/dist")] {
        println!("cargo:rerun-if-changed={}", dir.display());
    }

    let mut files = Vec::new();
    if let Some(bundle) = bundle_dir() {
        println!("cargo:rerun-if-changed={}", bundle.display());
        collect(&bundle, &bundle, &mut files);
        files.sort();
    } else {
        println!(
            "cargo:warning=craber-site: no web bundle found, so `craber build` and \
             `craber serve` will refuse at run time. Run `just web-build` (or set \
             CRABER_WEB_DIST) and rebuild."
        );
    }

    let mut generated = String::from(
        "// Generated by crates/craber-site/build.rs. Do not edit.\n\
         pub(crate) static FILES: &[(&str, &[u8])] = &[\n",
    );
    for (name, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        writeln!(
            generated,
            "    ({name:?}, include_bytes!(r\"{}\")),",
            path.display()
        )
        .expect("writing to a String");
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("bundle.rs");
    std::fs::write(&out, generated).expect("writing bundle.rs");
}

/// Where to look for the bundle, in order of how specific the answer is.
///
/// 1. `CRABER_WEB_DIST` — an explicit answer from whoever is driving the build.
///    A release job that builds the frontend once and then compiles the binary
///    for several targets sets this.
/// 2. `../../web/dist` — the workspace checkout. It only exists when someone
///    is working in this repository, and then it is by definition the freshest
///    thing available, so it beats the vendored copy. Putting the vendored copy
///    first would mean one `just vendor-bundle` silently freezes every later
///    local build against a stale frontend.
/// 3. `bundle/` inside this package — the vendored copy, and the only candidate
///    that survives `cargo package`: the others are outside the package
///    directory and a `.crate` tarball cannot contain them. `just
///    vendor-bundle` puts it there.
///
/// Returns the first that exists and holds something, so a stale empty
/// directory does not shadow a real bundle further down the list.
fn bundle_dir() -> Option<PathBuf> {
    let manifest =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));

    let candidates = [
        std::env::var_os("CRABER_WEB_DIST").map(PathBuf::from),
        Some(manifest.join("../../web/dist")),
        Some(manifest.join("bundle")),
    ];
    candidates
        .into_iter()
        .flatten()
        .find(|dir| dir.join("index.html").is_file())
}

/// Collects `(site path, absolute path)` pairs. Site paths use `/` because they
/// are URLs in `index.html` as much as they are filenames.
fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect(root, &path, out);
            continue;
        }
        // `web/public/schema.json` is whatever schema the dev server was last
        // pointed at. Embedding it would ship a stale diagram inside every
        // binary, and `write` overwrites it with the real one anyway.
        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };
        if relative == Path::new("schema.json") {
            continue;
        }
        let site_path = relative
            .components()
            .map(|c| c.as_os_str().to_string_lossy())
            .collect::<Vec<_>>()
            .join("/");
        out.push((site_path, path));
    }
}
